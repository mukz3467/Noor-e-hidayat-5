object HadithData {

    val collections = listOf(HadithCatalog.COLLECTION_BUKHARI, HadithCatalog.COLLECTION_MUSLIM)

    private fun bukhariItem(
        id: String,
        bookNumber: Int,
        hadithNumber: Int,
        chapterNumber: Int,
        chapterArabic: String,
        chapterEnglish: String,
        chapterUrdu: String,
        chapterHindi: String,
        textArabic: String,
        textEnglish: String,
        textUrdu: String,
        textHindi: String,
        narrator: String,
        grade: String = "Sahih (صحيح البخاري)",
        sourceAttribution: String = "Sahih al-Bukhari, Book $bookNumber, Hadith $hadithNumber"
    ): Hadith {
        val bookInfo = HadithCatalog.bukhari97Books.firstOrNull { it.bookNumber == bookNumber }
        val vol = bookInfo?.volumeNumber ?: 1
        val bName = bookInfo?.let { "Book $bookNumber: ${it.titleEn} (${it.titleAr})" } ?: "Book $bookNumber"
        return Hadith(
            id = id,
            collection = HadithCatalog.COLLECTION_BUKHARI,
            bookNumber = bookNumber,
            bookName = bName,
            hadithNumber = hadithNumber,
            chapterArabic = chapterArabic,
            chapterEnglish = chapterEnglish,
            chapterUrdu = chapterUrdu,
            chapterHindi = chapterHindi,
            textArabic = textArabic,
            textEnglish = textEnglish,
            textUrdu = textUrdu,
            textHindi = textHindi,
            narrator = narrator,
            grade = grade,
            sourceAttribution = sourceAttribution,
            volumeNumber = vol,
            chapterNumber = chapterNumber,
            sourceUrl = "https://sunnah.com/bukhari:$hadithNumber",
            editionName = "Curated 4-Language Core • ${HadithCatalog.bukhariManifest.volumeEditionName}",
            translatorName = "EN: Dr. M. Muhsin Khan • UR/HI: Authentic Bukhari Translation",
            licenseName = "Sunnah.com Reference & fawazahmed0/hadith-api (The Unlicense)",
            isHindiAvailable = true,
            isBundled = true
        )
    }

